import fs from "node:fs";
import path from "node:path";
import { clientConfigSchema, type ClientConfig } from "./schema";

/**
 * Loads this generated project's own client configuration. The generator
 * (factory/create-client.mjs) writes `client-config.json` at the project
 * root from the source YAML — the running app never reads YAML directly,
 * only this already-validated, already-typed JSON, so a malformed source
 * file can never reach runtime.
 */
let cached: ClientConfig | null = null;

export function loadClientConfig(): ClientConfig {
  if (cached) return cached;
  const configPath = path.resolve(process.cwd(), "client-config.json");
  if (!fs.existsSync(configPath)) {
    throw new Error(
      `client-config.json not found at ${configPath}. This file is generated by factory/create-client.mjs — a project created directly from templates/barbershop-booking/ without running the generator will not have it.`,
    );
  }
  const raw = JSON.parse(fs.readFileSync(configPath, "utf8"));
  cached = clientConfigSchema.parse(raw);
  return cached;
}

/** Test-only escape hatch — never used by application code. */
export function __setClientConfigForTests(config: ClientConfig | null) {
  cached = config;
}
